export function getDailyGames(dateStr) {
  const level   = getDifficultyLevel(dateStr);
  const packIdx = getWeekPack(dateStr);
  const pack    = weeklyPacks[packIdx];
  const seed    = dateStr.replace(/-/g,"").split("").reduce((a,c) => a + c.charCodeAt(0), 0);
  const pick    = (arr, off) => arr && arr.length ? arr[(seed + off) % arr.length] : null;

  const wrPool = pack.wordRecall[level] || pack.wordRecall[1];
  const trPool = pack.trivia[level]     || pack.trivia[1];
  const ptPool = pack.pattern[level]    || pack.pattern[1];

  return [
    { type: GAME_TYPES.WORD_RECALL, data: pick(wrPool, 0), level, showMs: wordRecallShowMs[level], packName: pack.name },
    { type: GAME_TYPES.TRIVIA,      data: pick(trPool, 1), level, packName: pack.name },
    { type: GAME_TYPES.PATTERN,     data: pick(ptPool, 2), level, packName: pack.name },
  ];
}

