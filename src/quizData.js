const LAUNCH = new Date("2026-06-27");

export function getDifficultyLevel(dateStr) {
  const dayNum = Math.max(0, Math.floor((new Date(dateStr) - LAUNCH) / 86400000));
  const pos = dayNum % 15;
  let base;
  if (pos < 3)  base = 1;
  else if (pos < 6)  base = 2;
  else if (pos < 9)  base = 3;
  else if (pos < 12) base = 4;
  else base = 5;
  return Math.min(5, base + 2);
}

export function getWeekNumber(dateStr) {
  return Math.floor(Math.max(0, Math.floor((new Date(dateStr) - LAUNCH) / 86400000)) / 7);
}
export function getWeekPack(dateStr) {
  return getWeekNumber(dateStr) % 5;
}

